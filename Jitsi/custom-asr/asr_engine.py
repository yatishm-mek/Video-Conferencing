"""
Moonshine ASR engine for the Jitsi Vosk-protocol bridge.

Core model-loading + biased-transcription logic copied from
D:\\Realtime-ASR\\live_asr.py (load_model / transcribe / make_bias_processor /
highlight_terms), trimmed to drop the diarizer, mic I/O and report code that the
WebSocket server does not need. Speaker separation is NOT done here — Jigasi
already hands us one WebSocket per participant, so each stream is a single
speaker.

The fine-tuned checkpoint and the trie/vocab data are referenced by path so the
original project is never modified. Override with env vars:

    ASR_CHECKPOINT   path to the Moonshine checkpoint directory
                     (default: D:\\Realtime-ASR\\moonshine_medium_indian_english_v7\\checkpoint-550)
    ASR_TRIE         path to the trie json              (default: ./data/benchmark_trie.json)
    ASR_VOCAB        path to the tokenized vocab json   (default: ./data/benchmark_vocabulary_tokens.json)

Default skills set: the fixed 67-term benchmark vocabulary in ./data/ — this is
the server's stable default and is NOT touched by make_skills.py. Per-candidate
sets generated by make_skills.py are written to ./generated_skills/ and are only
used if you explicitly point ASR_VOCAB/ASR_TRIE at them.
"""

from __future__ import annotations

import json
import os
import re
import time
from pathlib import Path

import numpy as np
import torch
from transformers import (
    AutoProcessor,
    LogitsProcessorList,
    MoonshineStreamingForConditionalGeneration,
)

from contextual_bias_processor import InterviewContextLogitsProcessor

HERE = Path(__file__).resolve().parent

# --- paths (override via env) ------------------------------------------------
DEFAULT_CHECKPOINT = Path(
    os.environ.get(
        "ASR_CHECKPOINT",
        # Local, self-contained copy of the fine-tuned checkpoint (inference files
        # only; training_state.pt omitted). Override with ASR_CHECKPOINT to point
        # back at D:\Realtime-ASR\moonshine_medium_indian_english_v7\checkpoint-550.
        str(HERE / "model"),
    )
)
TRIE_PATH = Path(os.environ.get("ASR_TRIE", HERE / "data" / "benchmark_trie.json"))
VOCAB_PATH = Path(
    os.environ.get("ASR_VOCAB", HERE / "data" / "benchmark_vocabulary_tokens.json")
)

# --- model / decode config (mirrors live_asr.py) -----------------------------
SAMPLE_RATE = 16000
STRONG_BIAS = 1.0
MODERATE_BIAS = 0.5
MAX_PREFIX_LENGTH = 16
# Cap generation length. Utterances are short (VAD-chunked), so a lower cap
# bounds worst-case latency and stops runaway repetition loops from running to
# the old 96-token limit on CPU.
MAX_NEW_TOKENS = int(os.environ.get("ASR_MAX_NEW_TOKENS", "64"))
# Anti-repetition: stops "search is search is search is…" style loops, which
# both produce garbage and waste CPU time (latency). no_repeat_ngram_size blocks
# any N-gram from repeating; repetition_penalty discourages re-emitting tokens.
NO_REPEAT_NGRAM = int(os.environ.get("ASR_NO_REPEAT_NGRAM", "3"))
REPETITION_PENALTY = float(os.environ.get("ASR_REPETITION_PENALTY", "1.3"))

DEVICE = torch.device("cuda" if torch.cuda.is_available() else "cpu")


def load_model(checkpoint: Path = DEFAULT_CHECKPOINT):
    print(f"[engine] Loading fine-tuned model: {checkpoint}")
    print(
        f"[engine] Device: {DEVICE}"
        + (f" ({torch.cuda.get_device_name(0)})" if DEVICE.type == "cuda" else "")
    )
    processor = AutoProcessor.from_pretrained(str(checkpoint))
    model = MoonshineStreamingForConditionalGeneration.from_pretrained(
        str(checkpoint)
    ).to(DEVICE)
    model.eval()
    # OPT-IN only (ASR_QUANTIZE=1). Dynamic int8 quantization can speed up CPU
    # inference 2-3x on modern x86, BUT the int8 kernels require AVX2 — on CPUs
    # without it (same machines that log "NNPACK ... Unsupported hardware") the
    # quantized forward pass crashes the process with SIGILL (illegal
    # instruction). So it is DISABLED by default and must be explicitly enabled
    # only on hardware known to support AVX2.
    if DEVICE.type == "cpu" and os.environ.get("ASR_QUANTIZE", "0") in ("1", "true", "True"):
        try:
            model = torch.quantization.quantize_dynamic(
                model, {torch.nn.Linear}, dtype=torch.qint8
            )
            print("[engine] applied dynamic int8 quantization (CPU speedup)")
        except Exception as e:  # pragma: no cover
            print(f"[engine] quantization skipped ({e})")
    return processor, model


def make_bias_processor():
    trie_data = json.loads(Path(TRIE_PATH).read_text(encoding="utf-8"))
    tokenized_terms = json.loads(
        Path(VOCAB_PATH).read_text(encoding="utf-8")
    )["terms"]
    return trie_data, tokenized_terms


def transcribe(model, processor, audio, trie_data, tokenized_terms, use_bias=True):
    """audio: float32 mono @ 16 kHz. Returns (text, seconds)."""
    inputs = processor(audio, sampling_rate=SAMPLE_RATE, return_tensors="pt")
    inputs = {
        k: (v.to(DEVICE) if torch.is_tensor(v) else v) for k, v in inputs.items()
    }

    logits_processor = None
    if use_bias:
        bp = InterviewContextLogitsProcessor(
            trie_data=trie_data,
            tokenized_terms=tokenized_terms,
            strong_bias=STRONG_BIAS,
            moderate_bias=MODERATE_BIAS,
            max_prefix_length=MAX_PREFIX_LENGTH,
        )
        logits_processor = LogitsProcessorList([bp])

    gen_kwargs = dict(
        max_new_tokens=MAX_NEW_TOKENS,
        logits_processor=logits_processor,
    )
    if NO_REPEAT_NGRAM > 0:
        gen_kwargs["no_repeat_ngram_size"] = NO_REPEAT_NGRAM
    if REPETITION_PENALTY and REPETITION_PENALTY != 1.0:
        gen_kwargs["repetition_penalty"] = REPETITION_PENALTY

    t0 = time.perf_counter()
    with torch.inference_mode():
        generated = model.generate(**inputs, **gen_kwargs)
    dt = time.perf_counter() - t0
    text = processor.batch_decode(generated, skip_special_tokens=True)[0].strip()
    return text, dt


def _term_regex(term):
    parts = term.lower().split()
    return (
        r"(?<![A-Za-z0-9])"
        + r"\s+".join(re.escape(p) for p in parts)
        + r"(?![A-Za-z0-9])"
    )


def find_terms(text, tokenized_terms):
    """Return the biasing terms present in text (boundary-aware)."""
    found = []
    for term in {t["term"] for t in tokenized_terms if t.get("valid")}:
        if re.search(_term_regex(term), text, flags=re.IGNORECASE):
            found.append(term)
    return found
